"""
Writes packages/shared/src/philfctFoods.ts: every food in DOST-FNRI's Philippine Food Composition Table
(PhilFCT) with its calories and protein per 100 g, so food search finds Filipino food offline.

The data comes from https://github.com/nedpals/fct-fnri-api (CC0), a JSON copy of the PhilFCT website.

    git clone --depth 1 https://github.com/nedpals/fct-fnri-api /tmp/fct
    python3 tools/philfct/build.py /tmp/fct
"""
import json
import re
import sys
from pathlib import Path

# PhilFCT's short forms, spelled out so the names read well and search finds "leaves", "canned" and so on.
WORDS = {
    'lvs': 'leaves', 'cnd': 'canned', 'flvr': 'flavored', 'flvrd': 'flavored', 'prep': 'preparation', 'drnk': 'drink',
    'jce': 'juice', 'pwdr': 'powder', 'cond': 'condensed', 'conc': 'concentrate', 'grtd': 'grated', 'sce': 'sauce',
    'inst': 'instant', 'veg': 'vegetable', 'choc': 'chocolate', 'w/': 'with', 'w/o': 'without',
}


def tidy(text: str) -> str:
    text = re.sub(r'(?<![\w/])(w/o|w/)(?=\s)', lambda m: WORDS[m.group(1)], text)
    return re.sub(r'\b[a-z]+\b', lambda m: WORDS.get(m.group(0), m.group(0)), text).strip()


def main(repo: str) -> None:
    out = []
    for path in sorted(Path(repo, 'data', 'foods').glob('[A-Z]*.json')):
        food = json.loads(path.read_text())
        kcal = next((m['value'] for m in food.get('measurements', []) if m.get('unit') == 'kcal'), None)
        protein = next((n['value'] for n in food['nutrients'] if n['key'] == 'protein_g'), 0) or 0
        if kcal is None or not 0 < kcal <= 900:  # salt (0 kcal) is not worth logging
            continue
        name = tidy(food['name'])
        alt = (food.get('alternative_name') or '').strip()
        if alt and alt != 'N/A' and alt.lower() not in name.lower():
            name = f'{name} ({alt})'
        if len(name) > 80:
            name = name[:79] + '…'
        out.append(f"  [{json.dumps(food['id'])}, {json.dumps(name, ensure_ascii=False)}, {round(kcal, 1):g}, {round(min(100, protein), 1):g}],")

    target = Path(__file__).resolve().parents[2] / 'packages/shared/src/philfctFoods.ts'
    target.write_text(
        '// Generated by tools/philfct/build.py from DOST-FNRI PhilFCT (via github.com/nedpals/fct-fnri-api). Do not edit.\n'
        '// [PhilFCT food ID, name (Filipino name), kcal per 100 g, protein g per 100 g]\n'
        'export const PHILFCT_ROWS: readonly (readonly [string, string, number, number])[] = [\n'
        + '\n'.join(out) + '\n];\n'
    )
    print(f'{len(out)} foods → {target}')


if __name__ == '__main__':
    main(sys.argv[1])
